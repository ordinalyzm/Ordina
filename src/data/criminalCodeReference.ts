export function findCriminalArticle(query: string): CriminalCodeArticle | undefined {
  if (!query) return undefined;
  const match = query.match(/\d+(?:\.\d+)?/);
  const targetNum = match ? match[0] : query.trim();
  return CRIMINAL_CODE_DATA.find((item) => item.number === targetNum || query.includes(item.number));
}
