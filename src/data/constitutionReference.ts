export function findArticleByNumber(query: string | number): ConstitutionArticle | undefined {
  if (!query) return undefined;
  const numStr = query.toString().replace(/[^0-9]/g, '');
  return CONSTITUTION_DATA.find((item) => {
    const itemNum = item.number.toString().replace(/[^0-9]/g, '');
    return itemNum === numStr || item.number.toString() === query.toString();
  });
}
