export function findAdministrativeArticle(numberStr: string): AdministrativeCodeArticle | undefined {
  if (!numberStr) return undefined;
  const clean = numberStr.trim().replace(/^ст(\.|атья)?\s*/i, '').replace(/\s*коап(\s*рф)?/i, '');
  const directMatch = ADMINISTRATIVE_CODE_DATA.find((item) => item.number === clean);
  if (directMatch) return directMatch;
  return ADMINISTRATIVE_CODE_DATA.find((item) => numberStr.includes(item.number));
}
